#!/usr/bin/env python3
"""Sync the publication list from assets/data/publications.json into
   1. cv/publications.tex   (the CV's publication section), and
   2. index.html            (the Reference chapter of the website).

One record, two outputs: edit the JSON, then run `make` in cv/ (or this script).

Copyright (c) 2026 Boyang Cheng. MIT License (see ../LICENSE).
"""
import html
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SRC = ROOT / "assets" / "data" / "publications.json"
TEX_OUT = HERE / "publications.tex"
SITE = ROOT / "index.html"

ME = "Boyang Cheng"
MAX_AUTHORS = 8          # on the CV, longer lists are cut to "et al." (always keeping ME)

# full venue text (substring, case-insensitive) -> short form for the CV.
# Order matters: more specific names first ("Systems II" before "Systems I").
VENUES = [
    ("Journal of Solid-State Circuits", "IEEE JSSC"),
    ("Circuits and Systems II", "IEEE TCAS-II"),
    ("Circuits and Systems I", "IEEE TCAS-I"),
    ("Internet of Things Journal", "IEEE IoT-J"),
    ("Microelectronics Journal", "Microelectronics Journal"),
    ("Integration", "Integration, the VLSI Journal"),
    ("International Solid-State Circuits Conference", "ISSCC"),
    ("VLSI Technology and Circuits", "VLSI Symposium"),
    ("Design Automation Conference", "DAC"),
    ("Computer-Aided Design", "ICCAD"),
    ("Low Power Electronics and Design", "ISLPED"),
    ("Design, Automation & Test in Europe", "DATE"),
]

TEX_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    "µ": r"\textmu{}", "μ": r"\textmu{}",
    # narrow/thin spaces that show up in titles copied from publishers ("65 nm", "7.13 nJ")
    " ": r"\,", " ": r"\,", " ": r"\,", " ": r"\,", " ": "~",
}


# ---------------------------------------------------------------- helpers
def tex(text):
    return "".join(TEX_ESCAPES.get(ch, ch) for ch in text)


def kind(p):
    v = p.get("venue", "")
    if re.search(r"Dissertation", v, re.I):
        return None                      # the CV lists it under Education
    if re.search(r"Patent", v, re.I):
        return "patent"
    if re.search(r"arXiv", v, re.I):
        return "preprint"
    if re.search(r"Journal|Transactions|Letters|Integration", v, re.I):
        return "journal"
    return "conference"


def short_venue(v):
    for needle, short in VENUES:
        if needle.lower() in v.lower():
            return short
    return v


def initials(name):
    parts = name.split()
    if len(parts) == 1:
        return name
    return " ".join(w[0] + "." for w in parts[:-1]) + " " + parts[-1]


# ---------------------------------------------------------------- CV (LaTeX)
def cv_authors(raw):
    names = [a.strip() for a in raw.split(",") if a.strip()]
    keep = len(names)
    if len(names) > MAX_AUTHORS:
        mine = next((i for i, n in enumerate(names) if n.lower() == ME.lower()), 0)
        keep = max(MAX_AUTHORS - 2, mine + 1)
    out = []
    for n in names[:keep]:
        s = tex(initials(n))
        out.append(rf"\me{{{s}}}" if n.lower() == ME.lower() else s)
    return ", ".join(out) + (", et al." if keep < len(names) else "")


def cv_entry(p, k):
    venue = p.get("venue", "")
    if k == "journal":
        where = rf"\textit{{{tex(short_venue(venue))}}}"
        if "accepted" in venue.lower():
            where += ", accepted"
    elif k == "conference":
        where = rf"in \textit{{Proc.\ {tex(short_venue(venue))}}}"
    elif k == "preprint":
        where = rf"\textit{{arXiv:{p['arxiv']}}}" if p.get("arxiv") else rf"\textit{{{tex(venue)}}}"
        m = re.search(r"submitted to ([^)]+)", venue)
        if m:
            where += rf", submitted to \textit{{{tex(short_venue(m.group(1)))}}}"
    else:  # patent
        where = tex(venue.replace("Patent (US)", "U.S. Patent"))
    note = rf" \textbf{{({tex(p['note'])})}}" if p.get("note") else ""
    return rf"  \item {cv_authors(p.get('authors', ''))}, ``{tex(p['title'])},'' {where}, {p.get('year', '')}.{note}"


def write_cv(data):
    groups = {"journal": [], "conference": [], "preprint": [], "patent": []}
    for p in data["publications"]:
        k = kind(p)
        if k:
            groups[k].append(cv_entry(p, k))
    lines = [
        "% Generated by sync_publications.py from assets/data/publications.json.",
        "% Do not edit by hand: edit the JSON and run `make` in cv/.",
    ]
    for key, heading, label in [("journal", "Journal Articles", "J"), ("conference", "Conference Papers", "C"),
                                ("preprint", "Preprints", "P"), ("patent", "Patents", "T")]:
        if groups[key]:
            lines += [rf"\pubgroup{{{heading}}}", rf"\begin{{publist}}{{{label}}}", *groups[key], r"\end{publist}"]
    TEX_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return ", ".join(f"{len(v)} {k}" for k, v in groups.items())


# ---------------------------------------------------------------- website (HTML)
def write_site(data):
    e = lambda s: html.escape(str(s), quote=True)
    ext = 'target="_blank" rel="noopener noreferrer"'
    items = []
    for p in data["publications"]:
        href = (p.get("scholar_url")
                or (f"https://doi.org/{p['doi']}" if p.get("doi") else None)
                or (f"https://arxiv.org/abs/{p['arxiv']}" if p.get("arxiv") else data["source_url"]))
        au = e(p["authors"]).replace(ME, f"<b>{ME}</b>")
        venue = e(", ".join(v for v in [p.get("venue"), str(p["year"]) if p.get("year") else ""] if v))
        links = []
        if p.get("arxiv"):
            links.append(f'<a href="https://arxiv.org/abs/{e(p["arxiv"])}" {ext}>arXiv</a>')
        if p.get("doi"):
            links.append(f'<a href="https://doi.org/{e(p["doi"])}" {ext}>DOI</a>')
        tail = (' <span class="links">' + " · ".join(links) + "</span>") if links else ""
        note = f' <span class="note">{e(p["note"])}</span>' if p.get("note") else ""
        items.append("          <li>\n"
                     f'            <span class="t"><a href="{e(href)}" {ext}>{e(p["title"])}</a>{note}</span>\n'
                     f'            <p class="au">{au}</p>\n'
                     f'            <p class="v">{venue}{tail}</p>\n'
                     "          </li>")
    page = SITE.read_text(encoding="utf-8")
    new, n = re.subn(r'        <ol class="pubs">\n.*?\n        </ol>\n',
                     lambda m: '        <ol class="pubs">\n' + "\n".join(items) + "\n        </ol>\n", page, flags=re.S)
    if n != 1:
        raise SystemExit('index.html: could not find the <ol class="pubs"> list')
    if new != page:
        SITE.write_text(new, encoding="utf-8")
    return len(items)


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    print(f"cv/publications.tex: {write_cv(data)}")
    print(f"index.html: {write_site(data)} entries")


if __name__ == "__main__":
    main()
